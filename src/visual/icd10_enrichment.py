def build_clinical_scenes(topic: str) -> tuple[dict[str, Any], dict[str, Any]]:
    """依 SCENE23_ROWS 組出該疾病的場景 2（contrast）與場景 3（timeline）。"""
    if topic not in SCENE23_BY_TOPIC:
        raise ValueError(f"場景 2／3 知識缺漏：{topic}")
    (_t, lm, rm, lt, ln, lc, lf, rt, rn, rf,
     s2t, s2c, s2l1, s2l2,
     conn, s3t, s3c, m1, m2, m3, s3l1, s3l2) = SCENE23_BY_TOPIC[topic]
    scene2 = {
        "blueprint": "contrast",
        "title": s2t,
        "caption": s2c,
        "labels": [{"text": s2l1, "tone": "warning"}, {"text": s2l2, "tone": "optimal"}],
        "params": {
            "left": {"title": lt, "note": ln, "mode": lm, "core_effect": "none",
                     "core_label": lc, "footnote": lf, "unit_fill": "warn"},
            "right": {"title": rt, "note": rn, "mode": rm, "rows": 3, "per_row": 5,
                      "footnote": rf, "unit_fill": "ok"},
        },
    }
    scene3 = {
        "blueprint": "timeline",
        "title": s3t,
        "caption": s3c,
        "labels": [{"text": s3l1, "tone": "optimal"}, {"text": s3l2, "tone": "neutral"}],
        "params": {
            "milestones": [m1, m2, m3],
            "unit_effect": "steady",
            "connectors": conn,
            "units": 3,
            "unit_fill": "ok",
        },
    }
    return scene2, scene3


def validate_summary(summary: Any) -> tuple[bool, str]:
    """檢驗四段式臨床摘要：鍵集合完全一致、長度有界、零阿拉伯數字、無保證用語、無劑量或處方句型。

    回傳 (ok, code)；code 為固定英文代碼，不回傳原文。
    """
    if not isinstance(summary, dict) or set(summary.keys()) != set(SUMMARY_KEYS):
        return False, "summary_schema"
    for key in SUMMARY_KEYS:
        text = summary[key]
        if not isinstance(text, str) or not (_SUMMARY_MIN_LEN <= len(text.strip()) <= _SUMMARY_MAX_LEN):
            return False, "summary_length"
        if _DIGIT_RE.search(text):
            return False, "arabic_digit"
        if any(phrase in text for phrase in _FORBIDDEN_IN_SUMMARY):
            return False, "forbidden_phrase"
        ok, _reason = validate_single_faq({"question": "摘要檢驗", "answer": text}, check_dosage=True)
        if not ok:
            return False, "dosage_or_price"
    return True, "ok"


def build_pathology_scene(prev_scene: dict[str, Any], specialty: str, knowledge: tuple) -> dict[str, Any]:
    """以既有 Scene 1（保留標題、說明與標籤）與離線知識，組出 pathology_mechanism 場景。"""
    organ, lesion, trigger, defense, severity, accent, _summary = knowledge
    old_steps = prev_scene.get("params", {}).get("step_labels") or []
    if len(old_steps) != 3:
        raise ValueError("既有 Scene 1 的 step_labels 必須為 3 項")
    return {
        "blueprint": "pathology_mechanism",
        "title": prev_scene["title"],
        "caption": prev_scene["caption"],
        "labels": copy.deepcopy(prev_scene["labels"]),
        "params": {
            "organ_system": SYSTEM_BY_SPECIALTY[specialty],
            "organ_label": organ,
            "lesion_label": lesion,
            "trigger_label": trigger,
            "defense_label": defense,
            "severity_level": severity,
            "accent_fill": accent,
            "step_labels": list(old_steps),
        },
    }


def enrich_entry(entry: dict[str, Any], knowledge: Optional[tuple] = None) -> dict[str, Any]:
    """以離線知識升級單筆條目：Scene 1 改為 pathology_mechanism，並寫入 clinical_summary。

    回傳新物件（不改動輸入）。知識缺漏或摘要未通過檢驗即拋出 ValueError。
    """
    topic = entry["topic_key"]
    know = knowledge if knowledge is not None else OFFLINE_KNOWLEDGE.get(topic)
    if know is None:
        raise ValueError(f"離線知識庫缺少主題：{topic}")
    summary = dict(zip(SUMMARY_KEYS, know[6]))
    ok, code = validate_summary(summary)
    if not ok:
        raise ValueError(f"離線摘要未通過檢驗（{topic}）：{code}")

    out = copy.deepcopy(entry)
    out["ir"]["scenes"][0] = build_pathology_scene(out["ir"]["scenes"][0], entry["specialty"], know)
    out["ir"]["scenes"][1], out["ir"]["scenes"][2] = build_clinical_scenes(topic)
    out["clinical_summary"] = summary
    return out


def build_llm_prompt(entry: dict[str, Any]) -> str:
    """組出本地 LLM 萃取四段式摘要的提示詞（要求只輸出 JSON，禁止阿拉伯數字、劑量與價格）。"""
    return (
        "你是台灣基層診所的衛教內容編輯。請針對下列疾病，以繁體中文輸出一個 JSON 物件，"
        "鍵必須為 pathophysiology、clinical_presentation、management_care、red_flags_prevention，"
        "值為每段 20 至 120 字的純文字。規則：不得使用阿拉伯數字；不得提及任何藥名、劑量、價格；"
        "不得使用保證療效用語；紅旗警訊需包含具體症狀與就醫動作。只輸出 JSON，不要其他說明。\n"
        f"疾病：{entry['ir']['title']}\n"
        f"關鍵字：{'、'.join(entry['ir']['keywords'])}"
    )


def parse_llm_summary(raw: str) -> dict[str, str]:
    """從 LLM 輸出擷取 JSON 物件；無法解析或鍵不完整即拋出 ValueError。"""
    match = re.search(r"\{.*\}", raw, flags=re.DOTALL)
    if not match:
        raise ValueError("LLM 輸出不含 JSON 物件")
    data = json.loads(match.group(0))
    if not isinstance(data, dict):
        raise ValueError("LLM 輸出 JSON 非物件")
    return {k: data.get(k) for k in SUMMARY_KEYS}


def enrich_with_llm(
    entry: dict[str, Any],
    llm_call: Callable[[str], str],
) -> tuple[dict[str, Any], str]:
    """以本地 LLM 萃取摘要；任何失敗（呼叫、解析或檢驗）即退回離線知識庫。

    回傳 (條目, 來源)，來源為 "llm" 或 "offline_fallback"。
    """
    try:
        summary = parse_llm_summary(llm_call(build_llm_prompt(entry)))
        ok, _code = validate_summary(summary)
        if not ok:
            raise ValueError("llm_summary_invalid")
    except Exception:  # noqa: BLE001 — 任何失敗都退回離線權威來源，且不洩漏原始輸出
        return enrich_entry(entry), "offline_fallback"

    know = OFFLINE_KNOWLEDGE[entry["topic_key"]]
    out = copy.deepcopy(entry)
    out["ir"]["scenes"][0] = build_pathology_scene(out["ir"]["scenes"][0], entry["specialty"], know)
    out["ir"]["scenes"][1], out["ir"]["scenes"][2] = build_clinical_scenes(entry["topic_key"])
    out["clinical_summary"] = summary
    return out, "llm"
